def cmd_validate(args: argparse.Namespace) -> int:
    root = find_extension_root()
    if root is None:
        print("Error: not inside a Hacknet extension (no ExtensionInfo.xml found).", file=sys.stderr)
        return 1

    print(f"Validating extension at: {root}")
    errors = []
    warnings = []

    # Required file
    info_path = root / "ExtensionInfo.xml"
    if not info_path.is_file():
        errors.append("Missing ExtensionInfo.xml")
    else:
        try:
            tree = ET.parse(info_path)
            root_elem = tree.getroot()
            if root_elem.tag != "HacknetExtension":
                errors.append("ExtensionInfo.xml root tag must be <HacknetExtension>")
            # Basic presence checks
            for tag in ("Name", "Language"):
                if root_elem.find(tag) is None:
                    warnings.append(f"ExtensionInfo.xml is missing <{tag}>")
        except ET.ParseError as e:
            errors.append(f"ExtensionInfo.xml is not well-formed XML: {e}")

    # Standard folders
    expected_folders = [
        "Actions", "Factions", "HackerScripts", "Missions",
        "Music", "Nodes", "People", "Themes", "Web",
    ]
    for folder in expected_folders:
        if not (root / folder).is_dir():
            warnings.append(f"Missing recommended folder: {folder}/")

    # Check a few XML files for well-formedness
    for pattern in ("Nodes/*.xml", "Missions/*.xml", "Actions/*.xml", "Factions/*.xml"):
        for xml_file in root.glob(pattern):
            try:
                ET.parse(xml_file)
            except ET.ParseError as e:
                errors.append(f"{xml_file.relative_to(root)} is not well-formed: {e}")

    if errors:
        print("\nERRORS:")
        for e in errors:
            print(f"  ✗ {e}")
    if warnings:
        print("\nWARNINGS:")
        for w in warnings:
            print(f"  ⚠ {w}")

    if not errors and not warnings:
        print("\n✓ Project looks good!")
        return 0
    if errors:
        print(f"\n{len(errors)} error(s) found.")
        return 1
    print(f"\n{len(warnings)} warning(s) – project should still load.")
    return 0


def cmd_info(args: argparse.Namespace) -> int:
    root = find_extension_root()
    if root is None:
        print("Not inside a Hacknet extension directory.")
        return 1

    print(f"Extension root: {root}")
    info_path = root / "ExtensionInfo.xml"
    if info_path.is_file():
        try:
            tree = ET.parse(info_path)
            elem = tree.getroot()
            name = elem.findtext("Name", default="(unnamed)")
            lang = elem.findtext("Language", default="?")
            desc = (elem.findtext("Description") or "").strip()[:80]
            print(f"Name:        {name}")
            print(f"Language:    {lang}")
            if desc:
                print(f"Description: {desc}{'…' if len(desc) == 80 else ''}")
        except ET.ParseError:
            print("ExtensionInfo.xml exists but is not valid XML.")

    # Quick counts
    counts = {
        "Nodes": len(list((root / "Nodes").glob("*.xml"))) if (root / "Nodes").is_dir() else 0,
        "Missions": len(list((root / "Missions").rglob("*.xml"))) if (root / "Missions").is_dir() else 0,
        "Actions": len(list((root / "Actions").glob("*.xml"))) if (root / "Actions").is_dir() else 0,
        "Factions": len(list((root / "Factions").glob("*.xml"))) if (root / "Factions").is_dir() else 0,
    }
    print("Content:")
    for k, v in counts.items():
        print(f"  {k}: {v}")
    return 0


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="ziexpand",
        description="ZiExpand – build Hacknet Extensions faster while keeping full control.",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")

    sub = parser.add_subparsers(dest="command", required=True)

    # new
    p_new = sub.add_parser("new", help="Scaffold a new extension project")
    p_new.add_argument("name", help="Name of the new extension folder")
    p_new.set_defaults(func=cmd_new)

    # gen
    p_gen = sub.add_parser("gen", help="Generate content files")
    gen_sub = p_gen.add_subparsers(dest="gen_type", required=True)

    # gen node
    p_node = gen_sub.add_parser("node", help="Generate a Computer/Node XML")
    p_node.add_argument("id", help="Node id (used in filenames and references)")
    p_node.add_argument("--name", help="Display name of the computer")
    p_node.add_argument("--ip", help="IP address (omit for random)")
    p_node.add_argument("--security", type=int, default=3, help="Security level (ports needed)")
    p_node.add_argument("--icon", default="laptop", help="Icon name (laptop, chip, etc.)")
    p_node.add_argument("--password", help="Admin password (omit for random)")
    p_node.add_argument("--force", action="store_true", help="Overwrite existing file")
    p_node.set_defaults(func=cmd_gen_node)

    # gen mission
    p_mission = gen_sub.add_parser("mission", help="Generate a Mission XML")
    p_mission.add_argument("name", help="Mission file name (can include subfolders)")
    p_mission.add_argument("--title", help="Posting / mission title")
    p_mission.add_argument("--sender", help="Email sender")
    p_mission.add_argument("--subject", help="Email subject")
    p_mission.add_argument("--body", help="Email body text")
    p_mission.add_argument("--next", help="Next mission path (default NONE)")
    p_mission.add_argument("--force", action="store_true", help="Overwrite existing file")
    p_mission.set_defaults(func=cmd_gen_mission)

    # gen action
    p_action = gen_sub.add_parser("action", help="Generate a ConditionalActions XML")
    p_action.add_argument("name", help="Action set name")
    p_action.add_argument("--force", action="store_true", help="Overwrite existing file")
    p_action.set_defaults(func=cmd_gen_action)

    # gen faction
    p_faction = gen_sub.add_parser("faction", help="Generate a Faction XML")
    p_faction.add_argument("name", help="Faction file / id name")
    p_faction.add_argument("--display", help="Display name shown in-game")
    p_faction.add_argument("--force", action="store_true", help="Overwrite existing file")
    p_faction.set_defaults(func=cmd_gen_faction)

    # validate
    p_val = sub.add_parser("validate", help="Validate project structure and XML")
    p_val.set_defaults(func=cmd_validate)

    # info
    p_info = sub.add_parser("info", help="Show info about the current extension")
    p_info.set_defaults(func=cmd_info)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
