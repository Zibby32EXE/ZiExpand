def cmd_validate(args: argparse.Namespace) -> int:
    proj = load_project()
    if proj is None:
        print("Error: not inside a Hacknet extension (no ExtensionInfo.xml found).", file=sys.stderr)
        return 1

    print(f"Validating extension at: {proj.root}")
    result = validate_project(proj)

    for issue in result.issues:
        symbol = {"error": "✗", "warning": "⚠", "info": "•"}.get(issue.level, "•")
        loc = f"  ({issue.file})" if issue.file else ""
        print(f"  {symbol} {issue.message}{loc}")

    if result.errors:
        print(f"\n{len(result.errors)} error(s) found.")
        return 1
    if result.warnings:
        print(f"\n{len(result.warnings)} warning(s) – project should still load.")
        return 0
    print("\n✓ Project looks good!")
    return 0


def cmd_info(args: argparse.Namespace) -> int:
    proj = load_project()
    if proj is None:
        print("Not inside a Hacknet extension directory.")
        return 1

    print(f"Extension root: {proj.root}")
    print(f"Name:        {proj.name or '(unnamed)'}")
    print(f"Language:    {proj.language}")
    if proj.description:
        desc = proj.description[:100] + ("…" if len(proj.description) > 100 else "")
        print(f"Description: {desc}")
    if proj.starting_mission:
        print(f"Start mission: {proj.starting_mission}")
    print("Content:")
    print(f"  Nodes:         {len(proj.nodes)}")
    print(f"  Missions:      {len(proj.missions)}")
    print(f"  Actions:       {len(proj.actions)}")
    print(f"  Factions:      {len(proj.factions)}")
    print(f"  Themes:        {len(proj.themes)}")
    print(f"  People:        {len(proj.people)}")
    print(f"  HackerScripts: {len(proj.hackerscripts)}")
    return 0


def cmd_gui(args: argparse.Namespace) -> int:
    try:
        from .gui import run_gui
    except ImportError as e:
        print("Error: GUI requires Tkinter (usually included with Python).", file=sys.stderr)
        print(str(e), file=sys.stderr)
        return 1
    run_gui()
    return 0


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="ziexpand",
        description="ZiExpand – build Hacknet Extensions faster while keeping full control.",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")

    sub = parser.add_subparsers(dest="command", required=True)

    # new
    p_new = sub.add_parser("new", help="Scaffold a new extension project")
    p_new.add_argument("name", help="Name of the new extension folder")
    p_new.set_defaults(func=cmd_new)

    # gen
    p_gen = sub.add_parser("gen", help="Generate content files")
    gen_sub = p_gen.add_subparsers(dest="gen_type", required=True)

    p_node = gen_sub.add_parser("node", help="Generate a Computer/Node XML")
    p_node.add_argument("id", help="Node id")
    p_node.add_argument("--name", help="Display name")
    p_node.add_argument("--ip", help="IP address")
    p_node.add_argument("--security", type=int, default=3)
    p_node.add_argument("--icon", default="laptop")
    p_node.add_argument("--password", help="Admin password")
    p_node.add_argument("--ports", help="Comma-separated ports (default 22,21,25,80)")
    p_node.add_argument("--force", action="store_true")
    p_node.set_defaults(func=cmd_gen_node)

    p_mission = gen_sub.add_parser("mission", help="Generate a Mission XML")
    p_mission.add_argument("name", help="Mission file name (can include subfolders)")
    p_mission.add_argument("--title")
    p_mission.add_argument("--sender")
    p_mission.add_argument("--subject")
    p_mission.add_argument("--body")
    p_mission.add_argument("--next", help="Next mission path")
    p_mission.add_argument("--force", action="store_true")
    p_mission.set_defaults(func=cmd_gen_mission)

    p_action = gen_sub.add_parser("action", help="Generate a ConditionalActions XML")
    p_action.add_argument("name")
    p_action.add_argument("--force", action="store_true")
    p_action.set_defaults(func=cmd_gen_action)

    p_faction = gen_sub.add_parser("faction", help="Generate a Faction XML")
    p_faction.add_argument("name")
    p_faction.add_argument("--display")
    p_faction.add_argument("--force", action="store_true")
    p_faction.set_defaults(func=cmd_gen_faction)

    p_theme = gen_sub.add_parser("theme", help="Generate a Theme XML")
    p_theme.add_argument("name")
    p_theme.add_argument("--force", action="store_true")
    p_theme.set_defaults(func=cmd_gen_theme)

    p_person = gen_sub.add_parser("person", help="Generate a People entry")
    p_person.add_argument("name")
    p_person.add_argument("--display")
    p_person.add_argument("--force", action="store_true")
    p_person.set_defaults(func=cmd_gen_person)

    p_hs = gen_sub.add_parser("hackerscript", help="Generate a HackerScript .txt")
    p_hs.add_argument("name")
    p_hs.add_argument("--force", action="store_true")
    p_hs.set_defaults(func=cmd_gen_hackerscript)

    p_web = gen_sub.add_parser("web", help="Generate a Web page (HTML)")
    p_web.add_argument("name", nargs="?", default="index")
    p_web.add_argument("--force", action="store_true")
    p_web.set_defaults(func=cmd_gen_web)

    # validate / info / gui
    p_val = sub.add_parser("validate", help="Validate project structure, XML and references")
    p_val.set_defaults(func=cmd_validate)

    p_info = sub.add_parser("info", help="Show info about the current extension")
    p_info.set_defaults(func=cmd_info)

    p_gui = sub.add_parser("gui", help="Launch the graphical user interface")
    p_gui.set_defaults(func=cmd_gui)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
