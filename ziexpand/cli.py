from typing import Optional

from . import __version__
from .generators import (
    generate_action,
    generate_extension_info,
    generate_faction,
    generate_intro,
    generate_mission,
    generate_node,
)


def find_extension_root(start: Optional[Path] = None) -> Optional[Path]:
    """Walk up from start (or cwd) looking for ExtensionInfo.xml."""
    current = (start or Path.cwd()).resolve()
    for path in [current, *current.parents]:
        if (path / "ExtensionInfo.xml").is_file():
            return path
    return None


def cmd_new(args: argparse.Namespace) -> int:
    name = args.name.strip()
    if not name:
        print("Error: extension name cannot be empty.", file=sys.stderr)
        return 1

    target = Path(name)
    if target.exists():
        print(f"Error: directory '{name}' already exists.", file=sys.stderr)
        return 1

    # Create folder structure
    folders = [
        "Actions",
        "Factions",
        "HackerScripts",
        "Missions",
        "Music",
        "Nodes",
        "People",
        "Themes",
        "Web",
        "Web/Cache",
    ]
    target.mkdir(parents=True)
    for folder in folders:
        (target / folder).mkdir(parents=True, exist_ok=True)

    # Write core files
    (target / "ExtensionInfo.xml").write_text(
        generate_extension_info(name),
        encoding="utf-8",
    )
    (target / "Intro.txt").write_text(generate_intro(name), encoding="utf-8")

    # Placeholder note for logo
    (target / "Logo.png.placeholder").write_text(
        "Replace this file with your actual Logo.png (recommended size ~512x512).\n"
        "Delete this placeholder once you have a real logo.\n",
        encoding="utf-8",
    )

    # Minimal starting action so the project is valid out of the box
    (target / "Actions" / "StartingActions.xml").write_text(
        generate_action("StartingActions", instantly=True),
        encoding="utf-8",
    )

    # Minimal starting mission
    (target / "Missions" / "StartingMission.xml").write_text(
        generate_mission(
            "StartingMission",
            title="Getting Started",
            sender="ZiExpand",
            subject="Welcome",
            body=(
                "This is a starter mission generated by ZiExpand.\n"
                "Replace it with your own story!\n"
            ),
        ),
        encoding="utf-8",
    )

    print(f"Created new Hacknet extension: {target.resolve()}")
    print()
    print("Next steps:")
    print(f"  1. cd {name}")
    print("  2. Edit ExtensionInfo.xml (name, description, starting mission, etc.)")
    print("  3. Use 'ziexpand gen node/mission/action/faction' to add content")
    print("  4. Copy the folder into your Hacknet Extensions directory")
    print("  5. Launch Hacknet with -enabledebug for faster testing")
    return 0


def cmd_gen_node(args: argparse.Namespace) -> int:
    root = find_extension_root()
    if root is None:
        print("Error: not inside a Hacknet extension (no ExtensionInfo.xml found).", file=sys.stderr)
        return 1

    node_id = args.id.strip()
    if not node_id:
        print("Error: node id cannot be empty.", file=sys.stderr)
        return 1

    filename = f"{node_id}.xml"
    out_path = root / "Nodes" / filename
    if out_path.exists() and not args.force:
        print(f"Error: {out_path} already exists. Use --force to overwrite.", file=sys.stderr)
        return 1

    content = generate_node(
        node_id=node_id,
        name=args.name or node_id,
        ip=args.ip,
        security=args.security,
        icon=args.icon,
        admin_pass=args.password,
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    print(f"Generated node: {out_path.relative_to(root)}")
    return 0


def cmd_gen_mission(args: argparse.Namespace) -> int:
    root = find_extension_root()
    if root is None:
        print("Error: not inside a Hacknet extension (no ExtensionInfo.xml found).", file=sys.stderr)
        return 1

    name = args.name.strip()
    if not name:
        print("Error: mission name cannot be empty.", file=sys.stderr)
        return 1

    # Allow subfolders: Missions/Chapter1/Foo.xml
    if "/" in name or "\\" in name:
        rel = Path(name)
        if not str(rel).startswith("Missions"):
            rel = Path("Missions") / rel
    else:
        rel = Path("Missions") / f"{name}.xml"

    out_path = root / rel
    if out_path.exists() and not args.force:
        print(f"Error: {out_path} already exists. Use --force to overwrite.", file=sys.stderr)
        return 1

    content = generate_mission(
        name=name.split("/")[-1].replace(".xml", ""),
        title=args.title or name,
        sender=args.sender or "Unknown",
        subject=args.subject or "New Mission",
        body=args.body or "Mission details go here.\n",
        next_mission=args.next or "NONE",
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    print(f"Generated mission: {out_path.relative_to(root)}")
    return 0


