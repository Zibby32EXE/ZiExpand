"""XML and text template generators for Hacknet Extension files."""

from __future__ import annotations

from typing import Optional


def _esc(text: str) -> str:
    """Minimal XML text escaping."""
    return (
        text.replace("&", "&")
        .replace("<", "<")
        .replace(">", ">")
    )


def generate_extension_info(name: str) -> str:
    """Generate a ready-to-edit ExtensionInfo.xml."""
    return f"""<?xml version="1.0" encoding="UTF-8" ?>
<HacknetExtension>
    <!-- Language of the extension. Supported: en-us, de-de, fr-be, ru-ru, es-ar, ko-kr, ja-jp, zh-cn -->
    <Language>en-us</Language>

    <!-- Display name (max 128 characters) -->
    <Name>{_esc(name)}</Name>

    <!-- Whether the player can save during this extension -->
    <AllowSaves>true</AllowSaves>

    <!-- Nodes that are visible from the start (comma-separated ids) -->
    <StartingVisibleNodes></StartingVisibleNodes>

    <!-- Mission that loads when the extension starts -->
    <StartingMission>Missions/StartingMission.xml</StartingMission>

    <!-- Conditional action set loaded at session start (or NONE) -->
    <StartingActions>Actions/StartingActions.xml</StartingActions>

    <!-- Description shown in the Extensions menu -->
    <Description>
--- {_esc(name)} ---
A new Hacknet Extension created with ZiExpand.
Replace this description with your own story summary.
    </Description>

    <!-- Optional: list Faction files used by this extension -->
    <!-- <Faction>Factions/ExampleFaction.xml</Faction> -->

    <!-- Optional music (name without extension from Content/Music or Content/DLC/Music) -->
    <!-- <IntroStartupSong>The_Quickening</IntroStartupSong> -->
</HacknetExtension>
"""


def generate_intro(name: str) -> str:
    """Generate a simple Intro.txt."""
    return f"""Welcome to {name}.

This intro text appears when the extension is first launched.
Edit Intro.txt to set the mood and give the player their first context.

You can use multiple paragraphs.
"""


def generate_node(
    node_id: str,
    name: str = "Unnamed Computer",
    ip: Optional[str] = None,
    security: int = 3,
    icon: str = "laptop",
    admin_pass: Optional[str] = None,
    ports: str = "22, 21, 25, 80",
) -> str:
    """Generate a basic Computer/Node XML file."""
    ip_attr = f' ip="{ip}"' if ip else ""
    admin_line = f'    <adminPass pass="{_esc(admin_pass)}" />\n' if admin_pass else ""

    return f"""<?xml version="1.0" encoding="UTF-8" ?>
<!-- Node generated by ZiExpand. Edit freely – full official format is supported. -->
<Computer id="{_esc(node_id)}"
          name="{_esc(name)}"{ip_attr}
          security="{security}"
          allowsDefaultBootModule="true"
          icon="{_esc(icon)}"
          type="1">

{admin_line}    <!-- Ports the player must open (comma-separated). Common: 22,21,25,80,1433,443,104,6881 -->
    <ports>{ports}</ports>

    <!-- Optional: fixed accounts -->
    <!-- <account username="admin" password="password" type="0" /> -->
    <!-- <account username="#PLAYERNAME#" password="playerpass" type="2" /> -->

    <!-- Files on the computer -->
    <file path="home" name="readme.txt">Welcome to {_esc(name)}.
This file was generated by ZiExpand.
Replace or expand the content as needed.</file>

    <!-- Optional daemons (mail, web, etc.) -->
    <!-- <mailServer name="Mail Server" color="200,100,50" /> -->
    <!-- <daemon name="webServer" /> -->

    <!-- Linked nodes (for map connections) -->
    <!-- <linked id="otherNodeId" /> -->

</Computer>
"""


def generate_mission(
    name: str,
    title: str = "New Mission",
    sender: str = "Unknown",
    subject: str = "Mission Briefing",
    body: str = "Details go here.\n",
    next_mission: str = "NONE",
) -> str:
    """Generate a basic Mission XML file."""
    body_escaped = _esc(body)

    return f"""<?xml version="1.0" encoding="UTF-8" ?>
<!-- Mission generated by ZiExpand. Full official mission format is supported. -->
<mission activeCheck="false" shouldIgnoreSenderVerification="false">

    <goals>
        <!-- Add goal elements here. Examples:
        <goal type="filedeletion" target="targetNodeId" file="secret.txt" path="home" />
        <goal type="getadmin" target="targetNodeId" />
        <goal type="hasFlag" target="someFlag" />
        <goal type="filepresence" target="nodeId" file="data.sys" path="sys" />
        <goal type="clearfolder" target="nodeId" path="home" />
        -->
    </goals>

    <!-- Actions to run when the mission starts / ends (optional) -->
    <missionStart val="0" suppress="false"></missionStart>
    <missionEnd val="0"></missionEnd>

    <!-- Next mission after this one completes (path relative to extension root, or NONE) -->
    <nextMission IsSilent="false">{_esc(next_mission)}</nextMission>

    <!-- Optional branching missions -->
    <!--
    <branchMissions>
        <branch>Missions/BranchExample.xml</branch>
    </branchMissions>
    -->

    <posting title="{_esc(title)}" reqs="" requiredRank="0" difficulty="0" client="UNKNOWN" target="UNKNOWN">
{_esc(title)}

Accept this mission to begin.
    </posting>

    <email>
        <sender>{_esc(sender)}</sender>
        <subject>{_esc(subject)}</subject>
        <body>{body_escaped}</body>
        <attachments>
            <!-- Optional: <link comp="nodeId" /> <account comp="nodeId" user="user" pass="pass" /> <note>text</note> -->
        </attachments>
    </email>

</mission>
"""


def generate_action(name: str, instantly: bool = True) -> str:
    """Generate a basic ConditionalActions XML file."""
    return f"""<?xml version="1.0" encoding="UTF-8" ?>
<!-- Conditional Actions set generated by ZiExpand. -->
<ConditionalActions>

    <!-- Runs immediately when this action file is loaded -->
    <Instantly needsMissionComplete="false">
        <!-- Example: give the player a flag -->
        <!-- <RunFunction FunctionName="addFlags:exampleFlag" /> -->

        <!-- Example: load another action set later -->
        <!-- <AddConditionalActions Filepath="Actions/AnotherSet.xml" /> -->

        <!-- Useful actions: changeMusic, launchExecutable, setFaction, addRank, etc. -->
        <!-- See the official Extensions Guide and community docs for the full list. -->
    </Instantly>

    <!-- Other useful conditions:
    <OnFlag flag="someFlag"> ... </OnFlag>
    <OnMissionComplete mission="Missions/Foo.xml"> ... </OnMissionComplete>
    <OnConnect target="nodeId"> ... </OnConnect>
    <OnDisconnect target="nodeId"> ... </OnDisconnect>
    -->

</ConditionalActions>
"""


def generate_faction(name: str, display_name: Optional[str] = None) -> str:
    """Generate a basic CustomFaction XML file."""
    display = display_name or name
    return f"""<?xml version="1.0" encoding="UTF-8" ?>
<!-- Faction generated by ZiExpand. -->
<CustomFaction name="{_esc(name)}" id="{_esc(name)}">

    <!-- Display name shown to the player -->
    <name>{_esc(display)}</name>

    <!-- Optional: value needed for next rank, actions on rank-up, etc. -->
    <!-- See official docs for full faction features. -->

</CustomFaction>
"""


def generate_theme(name: str) -> str:
    """Generate a basic Theme XML skeleton."""
    return f"""<?xml version="1.0" encoding="UTF-8" ?>
<!-- Theme generated by ZiExpand. Themes control background / UI styling. -->
<theme>
    <!-- Background image path relative to the extension (optional) -->
    <!-- <backgroundPath>Themes/{_esc(name)}_bg.png</backgroundPath> -->

    <!-- Layout / extra options – consult official docs for supported tags -->
    <!-- This is a minimal skeleton; expand as needed. -->
</theme>
"""


def generate_person(name: str, full_name: Optional[str] = None) -> str:
    """Generate a basic People entry."""
    display = full_name or name
    return f"""<?xml version="1.0" encoding="UTF-8" ?>
<!-- Person database entry generated by ZiExpand. -->
<Person id="{_esc(name)}" name="{_esc(display)}">
    <!-- Optional extra fields used by in-game databases -->
    <!-- <age>30</age> -->
    <!-- <job>System Administrator</job> -->
    <!-- <location>Unknown</location> -->
</Person>
"""


def generate_hackerscript(name: str) -> str:
    """Generate a basic HackerScript (.txt) skeleton."""
    return f"""# HackerScript: {name}
# Generated by ZiExpand.
#
# HackerScripts are executed line-by-line by the game when launched.
# Common commands: connect, probe, portscan, shell, overloads, etc.
# Refer to official / community documentation for the full command list.

# Example skeleton:
# connect targetNodeId
# probe
# portscan
# shell
"""


def generate_web_page(name: str = "index") -> str:
    """Generate a minimal XHTML page suitable for Hacknet web daemons."""
    return f"""<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0 Strict//EN"
    "http://www.w3.org/TR/xhtml1/DTD/xhtml1-strict.dtd">
<html>
<head>
    <meta http-equiv="Content-Type" content="text/html; charset=utf-8" />
    <title>{_esc(name)}</title>
    <!-- CSS must live under Web/Cache/ and be referenced relatively -->
    <!-- <link rel="stylesheet" href="Cache/style.css" type="text/css" /> -->
</head>
<body>
    <h1>{_esc(name)}</h1>
    <p>This page was generated by ZiExpand.</p>
    <p>All images and CSS must be placed in the Web/Cache folder (or a subfolder).</p>
</body>
</html>
"""
